/**
 * A session's mark: its icon (chosen to suit the project once it has a work schema) in the session's
 * colour, or its initials until then.
 */
export function SessionMark({ name, icon, color, size = 16, className }: { name: string; icon: SessionIconName | null; color?: string; size?: number; className?: string }) {
  const Icon = icon ? ICONS[icon] : null;
  const style = color ? ({ '--mark': color } as CSSProperties) : undefined;
  return Icon ? (
    <Icon className={['session-mark', className].filter(Boolean).join(' ')} style={style} size={size} strokeWidth={2} aria-hidden />
  ) : (
    <span className={['session-mark', 'session-mark-letters', className].filter(Boolean).join(' ')} style={style}>{monogram(name)}</span>
  );
}
